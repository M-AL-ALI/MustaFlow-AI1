function errorMessage(code: NabuFlowDatabaseErrorCode): string {
  switch (code) {
    case "configuration":
      return "The database runtime is not configured";
    case "invalid_query":
      return "The database request is invalid";
    case "conflict":
      return "The database request conflicts with existing data";
    case "timeout":
      return "The database request timed out";
    case "cancelled":
      return "The database request was cancelled";
    case "unavailable":
      return "The database is temporarily unavailable";
    case "policy_rejected":
      return "The database request was rejected by policy";
    case "internal":
      return "The database request could not be completed";
  }
}

