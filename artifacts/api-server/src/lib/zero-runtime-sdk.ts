function normalizePgResult(result: QueryResult): DatabaseStatementResult {
  return {
    command: result.command,
    rowCount: result.rowCount ?? 0,
    rows: result.rows as Array<Record<string, unknown>>,
  };
}

async function withClient<T>(
  pool: PgPool,
  signal: AbortSignal,
  operation: (client: PoolClient, destroy: () => void) => Promise<T>,
): Promise<T> {
  if (signal.aborted) throw new NabuFlowDirectDriverError("cancelled", false);
  let client: PoolClient;
  try {
    client = await pool.connect();
  } catch (error) {
    throw classifyPostgresError(error);
  }
  let destroyed = false;
  const destroy = () => {
    if (destroyed) return;
    destroyed = true;
    client.release(true);
  };
  const abort = () => destroy();
  signal.addEventListener("abort", abort, { once: true });
  try {
    if (signal.aborted) throw new NabuFlowDirectDriverError("cancelled", false);
    return await operation(client, destroy);
  } catch (error) {
    if (signal.aborted) throw new NabuFlowDirectDriverError("cancelled", false);
    throw classifyPostgresError(error);
  } finally {
    signal.removeEventListener("abort", abort);
    if (!destroyed) client.release();
  }
}

export const createNabuFlowFlyPostgresDriverFactory: DirectDatabaseDriverFactory =
  async (databaseUrl) => {
    let pg: PgModule;
    try {
      pg = (await import("pg")) as PgModule;
    } catch {
      throw new NabuFlowDirectDriverError("configuration", false);
    }
    const pool = new pg.Pool({
      connectionString: databaseUrl,
      max: 4,
      idleTimeoutMillis: 10_000,
      connectionTimeoutMillis: 10_000,
    });
    const driver: DirectDatabaseDriver = {
      async query(sql, params, options) {
        return withClient(pool, options.signal, async (client) =>
          normalizePgResult(await client.query(sql, params)),
        );
      },
      async atomicBatch(statements: DatabaseStatement[], options) {
        return withClient(pool, options.signal, async (client, destroy) => {
          let began = false;
          try {
            await client.query("BEGIN");
            began = true;
            const results: DatabaseStatementResult[] = [];
            for (const statement of statements) {
              if (options.signal.aborted) {
                destroy();
                throw new NabuFlowDirectDriverError("cancelled", false);
              }
              results.push(normalizePgResult(await client.query(statement.sql, statement.params)));
            }
            await client.query("COMMIT");
            return results;
          } catch (error) {
            if (began && !options.signal.aborted) {
              try {
                await client.query("ROLLBACK");
              } catch {
                destroy();
              }
            }
            throw error;
          }
        });
      },
    };
    return Object.freeze(driver);
  };

